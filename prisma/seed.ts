async function main() {
  console.log(`Seeding ${scholarships.length} scholarships...`);
  for (const s of scholarships) {
    // No natural unique key in the schema besides id, so key off name+org
    // for idempotent re-seeding.
    const existing = await prisma.scholarship.findFirst({
      where: { name: s.name, orgName: s.orgName },
      select: { id: true },
    });

    const data = {
      description: s.description,
      amountMin: s.amountMin,
      amountMax: s.amountMax,
      deadline: s.deadline,
      renewable: s.renewable,
      essayRequired: s.essayRequired,
      essayWordCount: s.essayWordCount,
      eligibilityTags: s.eligibilityTags,
      minGpa: s.minGpa,
      eligibleMajors: s.eligibleMajors ?? [],
      sourceUrl: s.sourceUrl,
      verified: true,
      lastVerifiedDate: new Date(),
      legitimacyScore: s.legitimacyScore,
    };

    if (existing) {
      await prisma.scholarship.update({ where: { id: existing.id }, data });
    } else {
      await prisma.scholarship.create({
        data: { name: s.name, orgName: s.orgName, eligibleStates: [], ...data },
      });
    }
  }
  console.log("Done.");
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
